function job(partial: JobInput): JobInput {
  return {
    transport: 'browser',
    browserConfigId: 'stock-headless',
    timeoutMs: 8_000,
    maxRetries: 0,
    backoffBaseMs: 120,
    backoffMaxMs: 2_000,
    captureScreenshot: true,
    ...partial,
  }
}

